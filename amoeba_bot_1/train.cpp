// amoeba_bot_1_train: self-play, training, and the gate that decides which
// model amoeba_bot_1 gets to play with. It never talks to Game Arena - it does
// not even link the SDK - and the player never trains. They share a checkpoint
// directory and nothing else, so running both at once is just running two
// programs, and killing either one leaves the other working.
//
// One generation is three steps:
//
//   1. play `AMOEBA_SELFPLAY_GAMES` games against itself with the champion, and
//      push every position into the replay buffer
//   2. take `AMOEBA_TRAIN_STEPS` gradient steps on batches drawn from the buffer
//   3. play the result against the champion; promote it only if it wins
//
// Step 3 is the point of the whole file. Training does not improve
// monotonically, so "the newest model" and "the strongest model" are different
// things, and an AlphaZero bug reliably produces a healthy-looking loss curve
// while the bot gets worse. A generation beating the one before it over a real
// match is the only honest signal here.
//
// Self-play is one game at a time. That is the obvious thing to fix first once
// the network exists: the evaluator interface already takes a span of boards, so
// the shape to move to is many concurrent games collecting leaves into one
// batched forward pass, rather than one position per pass.

