int main()
{
    const bot::Settings    settings;
    const bot::Checkpoints checkpoints = bot::Checkpoints::fromEnvironment();
    std::mt19937_64        rng(settings.seed);

    // Generation 0 is untrained, and is promoted without a match because there
    // is nothing yet for it to beat. It plays terribly; that is the baseline.
    if (checkpoints.latestGeneration() < 0)
    {
        bot::newNetwork(settings.seed)->save(checkpoints.forGeneration(0));
        checkpoints.promote(0);
        std::println("[train] wrote and promoted generation 0");
    }

    bot::ReplayBuffer buffer(static_cast<size_t>(settings.bufferCapacity));
    if (std::filesystem::exists(bot::bufferFile(checkpoints)))
    {
        buffer.load(bot::bufferFile(checkpoints));
        std::println("[train] recovered {} positions", buffer.size());
    }

    // One network trained continuously across generations. Resetting it to the
    // champion after a failed gate would throw that generation's training away,
    // and a plateau that takes two generations to cross would never be crossed.
    const std::unique_ptr<bot::Network> learner =
        bot::loadNetwork(checkpoints.forGeneration(checkpoints.latestGeneration()));
    bot::Trainer trainer(*learner);

    std::vector<bot::Sample> batch(static_cast<size_t>(settings.batchSize));

    for (;;)
    {
        // Read from disk rather than counting, so that a generation which was
        // skipped for want of data does not leave a hole in the numbering.
        const int generation = checkpoints.latestGeneration() + 1;

        const std::unique_ptr<bot::Network> champion = bot::loadNetwork(*checkpoints.best());

        for (int game = 0; game < settings.selfPlayGames; ++game)
            bot::selfPlay(*champion, settings, rng(), buffer);
        buffer.save(bot::bufferFile(checkpoints));
        std::println("[train] generation {}: {} games played, {} positions held",
                     generation, settings.selfPlayGames, buffer.size());

        if (buffer.size() < batch.size())
        {
            std::println("[train] not enough positions for a batch yet, playing more");
            continue;
        }

        float loss = 0.0f;
        for (int step = 0; step < settings.trainSteps; ++step)
        {
            buffer.drawBatch(batch, rng);
            loss = trainer.step(batch);
        }
        learner->save(checkpoints.forGeneration(generation));
        std::println("[train] generation {}: {} steps, loss {:.4f}", generation, settings.trainSteps, loss);

        const bot::MatchScore score = bot::playMatch(*learner, *champion, settings, rng());
        const bool            promoted = score.points() >= settings.gateThreshold;
        if (promoted)
            checkpoints.promote(generation);

        std::println("[train] generation {}: {}-{}-{} vs champion ({:.1f}%) - {}",
                     generation, score.wins, score.draws, score.losses, 100.0f * score.points(),
                     promoted ? "promoted" : "kept the champion");
    }
}
