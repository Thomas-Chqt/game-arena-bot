template <typename T>
T fromEnvironment(const char* name, T fallback)
{
    const char* text = std::getenv(name);
    if (text == nullptr)
        return fallback;

    T parsed{};
    if constexpr (std::is_floating_point_v<T>)
    {
        char* end = nullptr;
        parsed    = static_cast<T>(std::strtod(text, &end));
        if (end == text || *end != '\0')
        {
            std::println(stderr, "[train] {} is not a number, using {}", name, fallback);
            return fallback;
        }
    }
    else
    {
        const std::string_view value{text};
        if (std::from_chars(value.data(), value.data() + value.size(), parsed).ec != std::errc{})
        {
            std::println(stderr, "[train] {} is not a number, using {}", name, fallback);
            return fallback;
        }
    }
    return parsed;
}

struct Settings
{
    int selfPlayGames       = fromEnvironment("AMOEBA_SELFPLAY_GAMES", 200);
    int selfPlaySimulations = fromEnvironment("AMOEBA_SELFPLAY_SIMULATIONS", 400);
    int trainSteps          = fromEnvironment("AMOEBA_TRAIN_STEPS", 1000);
    int batchSize           = fromEnvironment("AMOEBA_BATCH", 512);
    int gateGames           = fromEnvironment("AMOEBA_GATE_GAMES", 100);
    int gateSimulations     = fromEnvironment("AMOEBA_GATE_SIMULATIONS", 400);

    // 55% is the usual bar: enough that a run of luck over 100 games does not
    // promote a model that is actually the same strength.
    float gateThreshold = fromEnvironment("AMOEBA_GATE_THRESHOLD", 0.55f);

    // How long a game samples its move from the visit counts instead of taking
    // the best one. Sampling is what makes two games differ; past the opening
    // it is just playing worse moves for no reason.
    int openingPlies = fromEnvironment("AMOEBA_OPENING_PLIES", 15);

    // Positions kept. A generation of 200 games contributes roughly 20k of them,
    // so this holds about the last 25 generations.
    int bufferCapacity = fromEnvironment("AMOEBA_BUFFER", 500000);

    uint64_t seed = fromEnvironment<uint64_t>("AMOEBA_SEED", 20260819);
};

// Self-play is bounded by its simulation count, not by the clock; this exists
// only so that an evaluator that wedges cannot hang the trainer forever.
constexpr std::chrono::minutes kSanityDeadline{5};

// ---------------------------------------------------------------------------
// Replay buffer
//
// A ring over the last N positions. Old positions are dropped rather than kept
// because they were generated by networks several generations weaker, and
// training on them holds the current one back.
// ---------------------------------------------------------------------------

class ReplayBuffer
{
public:
    explicit ReplayBuffer(size_t capacity) : m_capacity(capacity) {}

    size_t size() const { return m_samples.size(); }

    void push(const Sample& sample)
    {
        if (m_samples.size() < m_capacity)
            m_samples.push_back(sample);
        else
            m_samples[m_next] = sample;
        m_next = (m_next + 1) % m_capacity;
    }

    // With replacement: a batch of 512 out of 500k duplicates about nothing, and
    // sampling without replacement would need a shuffle of the whole buffer.
    void drawBatch(std::span<Sample> out, std::mt19937_64& rng) const
    {
        std::uniform_int_distribution<size_t> pick(0, m_samples.size() - 1);
        for (Sample& sample : out)
            sample = m_samples[pick(rng)];
    }

    // Written beside the file and renamed over it, so a crash halfway through
    // leaves the previous buffer intact rather than a truncated one.
    void save(const std::filesystem::path& file) const
    {
        std::filesystem::path staging = file;
        staging += ".staging";

        std::ofstream out(staging, std::ios::binary);
        out.write(reinterpret_cast<const char*>(m_samples.data()),
                  static_cast<std::streamsize>(m_samples.size() * sizeof(Sample)));
        out.close();

        std::filesystem::rename(staging, file);
    }

    void load(const std::filesystem::path& file)
    {
        const size_t available = std::filesystem::file_size(file) / sizeof(Sample);
        const size_t keep      = std::min(available, m_capacity);

        m_samples.resize(keep);
        std::ifstream in(file, std::ios::binary);
        in.seekg(static_cast<std::streamoff>((available - keep) * sizeof(Sample)));
        in.read(reinterpret_cast<char*>(m_samples.data()),
                static_cast<std::streamsize>(keep * sizeof(Sample)));

        m_next = keep % m_capacity;
    }

private:
    std::vector<Sample> m_samples;
    size_t              m_capacity;
    size_t              m_next = 0;
};

// ---------------------------------------------------------------------------
// Playing a game
// ---------------------------------------------------------------------------

struct GameRecord
{
    std::vector<std::pair<amoeba::Board, VisitCounts>> plies;
    amoeba::State                                      outcome;
};

// One game between two searches. Self-play passes the same evaluator twice and
// keeps the plies; the gate passes two different ones and reads only the
// outcome.
GameRecord playGame(Search& white, Search& black, int openingPlies, std::mt19937_64& rng)
{
    GameRecord            record;
    amoeba::Board         board = amoeba::openingBoard();
    std::vector<uint64_t> history{board.hash};

    while (board.state == amoeba::State::Ongoing)
    {
        Search&           search = board.whiteToMove ? white : black;
        const VisitCounts counts = search.run(board, history);
        record.plies.emplace_back(board, counts);

        const uint16_t move =
            board.ply < openingPlies ? sampleMove(counts, 1.0f, rng) : bestMove(counts);

        board = amoeba::apply(board, amoeba::Move::fromId(move), history);
        history.push_back(board.hash);
    }

    record.outcome = board.state;
    return record;
}

std::array<float, amoeba::kNumMoveIds> policyTarget(const VisitCounts& counts)
{
    const float total = static_cast<float>(std::accumulate(counts.begin(), counts.end(), uint64_t{0}));

    std::array<float, amoeba::kNumMoveIds> policy{};
    for (size_t id = 0; id < counts.size(); ++id)
        policy[id] = static_cast<float>(counts[id]) / total;
    return policy;
}

// Both sides are the same network. They still need two searches, because a
// Search owns its tree, and two different seeds, because sharing one would give
// White and Black the same stream of root noise.
void selfPlay(Evaluator& champion, const Settings& settings, uint64_t seed, ReplayBuffer& buffer)
{
    const auto config = [&](uint64_t searchSeed) {
        return Config{.simulations     = settings.selfPlaySimulations,
                      .deadline        = kSanityDeadline,
                      .rootNoiseWeight = 0.25f,
                      .seed            = searchSeed};
    };

    Search          white(champion, config(seed));
    Search          black(champion, config(seed ^ 0x9e3779b97f4a7c15ULL));
    std::mt19937_64 rng(seed);

    const GameRecord record = playGame(white, black, settings.openingPlies, rng);

    // The value target is the game's result seen by whoever was to move in that
    // position, which is what the search's own values mean. Signing it as "good
    // for White" instead would train a bot that plays badly on purpose for one
    // colour, and the loss curve would look fine throughout.
    for (const auto& [board, counts] : record.plies)
        buffer.push(Sample{board, policyTarget(counts), outcomeFor(record.outcome, board.whiteToMove)});
}

// ---------------------------------------------------------------------------
// The gate
// ---------------------------------------------------------------------------

struct MatchScore
{
    int wins   = 0;
    int draws  = 0;
    int losses = 0;

    float points() const
    {
        return (static_cast<float>(wins) + 0.5f * static_cast<float>(draws))
             / static_cast<float>(wins + draws + losses);
    }
};

// Colours alternate, because White moves first and that is worth something.
//
// Both sides play their best move, so the sampled opening is the only thing
// making one game differ from the next - without it the whole match would be a
// single game replayed `gateGames` times and the score would be 100% or 0%.
MatchScore playMatch(Evaluator& challenger, Evaluator& champion, const Settings& settings, uint64_t seed)
{
    MatchScore score;

    for (int game = 0; game < settings.gateGames; ++game)
    {
        const uint64_t gameSeed = seed + static_cast<uint64_t>(game);
        const Config   config{.simulations = settings.gateSimulations,
                              .deadline    = kSanityDeadline,
                              .seed        = gameSeed};

        Search challengerSearch(challenger, config);
        Search championSearch(champion, config);

        const bool challengerIsWhite = (game % 2) == 0;
        Search&    white             = challengerIsWhite ? challengerSearch : championSearch;
        Search&    black             = challengerIsWhite ? championSearch : challengerSearch;

        std::mt19937_64  rng(gameSeed);
        const GameRecord record = playGame(white, black, settings.openingPlies, rng);

        if (record.outcome == amoeba::State::Draw)
            ++score.draws;
        else if ((record.outcome == amoeba::State::WhiteWins) == challengerIsWhite)
            ++score.wins;
        else
            ++score.losses;
    }

    return score;
}

